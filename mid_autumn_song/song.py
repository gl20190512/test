def arrangement():
    """返回 (sections, total_beats)。

    sections: [(section_name, lines, chords, start_beat)]，lines 为 None 表示纯器乐段。
    """
    parts = [
        ("前奏", None, INTRO_CHORDS),
        ("主歌一", VERSE1, VERSE_CHORDS),
        ("副歌", CHORUS, CHORUS_CHORDS),
        ("主歌二", VERSE2, VERSE_CHORDS),
        ("副歌", CHORUS, CHORUS_CHORDS),
        ("副歌", CHORUS, CHORUS_CHORDS),
        ("尾奏", None, OUTRO_CHORDS),
    ]
    out, beat = [], 0.0
    for name, lines, chords in parts:
        out.append((name, lines, chords, beat))
        beat += 16 if lines is None else 32
    return out, beat
